suppressPackageStartupMessages({library(igraph);library(ggraph)})
e <- new.env(parent=globalenv());sys.source('R/grn.R',e)
df.grn2 <- data.frame(tf=c('RUNX1','G1','RUNX1','OTHER'),gene=c('G1','G2','G2','G3'),weights=c(.8,.6,.5,.3))
netobj <- igraph::graph_from_data_frame(df.grn2,directed=TRUE)
igraph::V(netobj)$type <- ifelse(igraph::V(netobj)$name %in% df.grn2$tf,'TF/Gene','Gene')
err <- tryCatch(e$NetCentPlot(netobj,'RUNX1'),error=identity)
stopifnot(inherits(err,'error'),grepl('connected',conditionMessage(err)))
cat('EXPECTED original graph error:',conditionMessage(err),'\n')
focus <- 'RUNX1'
focus.index <- match(focus,igraph::V(netobj)$name)
stopifnot(!is.na(focus.index))
cc <- igraph::components(netobj,mode='weak')
net.focus <- igraph::induced_subgraph(netobj,which(cc$membership==cc$membership[focus.index]))
p <- e$NetCentPlot(net.focus,gene=focus,highlights=focus)
b <- ggplot2::ggplot_build(p)
labels <- unlist(lapply(b$data,function(x) if('label' %in% names(x)) as.character(x$label) else character()))
stopifnot(igraph::is_connected(net.focus,mode='weak'), 'RUNX1' %in% labels,
          igraph::vcount(netobj)==5L,igraph::vcount(net.focus)==3L)
ggplot2::ggsave('/tmp/scmega-phase2-netcent.png',p,width=5,height=5,dpi=120)
cat('PASS: connected component plot builds and highlights RUNX1; original graph unchanged.\n')
